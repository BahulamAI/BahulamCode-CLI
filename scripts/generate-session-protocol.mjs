// Schema is the only source for the Node declarations and Rust wire structs.
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const schema = JSON.parse(fs.readFileSync(new URL('src/protocol/session-v2.schema.json', root)));
const check = process.argv.includes('--check');
const header = '// Generated by scripts/generate-session-protocol.mjs. Do not edit.\n';
function type(field, language) {
  if (Array.isArray(field.type)) return language === 'ts' ? 'string | null' : 'Option<String>';
  return ({ string: ['string', 'String'], integer: ['number', 'i64'], number: ['number', 'f64'], boolean: ['boolean', 'bool'], object: ['Record<string, unknown>', 'serde_json::Value'], array: ['unknown[]', 'Vec<serde_json::Value>'] }[field.type] || ['unknown', 'serde_json::Value'])[language === 'ts' ? 0 : 1];
}
function structure(name, definition, language) {
  const fields = Object.entries(definition.properties).map(([key, field]) => {
    const optional = !definition.required.includes(key);
    if (language === 'ts') return `  ${key}${optional ? '?' : ''}: ${type(field, language)};`;
    const value = type(field, language);
    const rustName = ['type', 'ref'].includes(key) ? `r#${key}` : key;
    return `${optional ? '    #[serde(default, skip_serializing_if = "Option::is_none")]\n' : ''}    pub ${rustName}: ${optional && !value.startsWith('Option<') ? `Option<${value}>` : value},`;
  }).join('\n');
  return language === 'ts' ? `export interface ${name} {\n${fields}\n}\n` : `#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]\npub struct ${name} {\n${fields}\n}\n`;
}
const events = Object.keys(schema['x-event-payloads']);
const commands = Object.keys(schema['x-command-payloads']);
let ts = header + `export type EventType = ${events.map(JSON.stringify).join(' | ')};\nexport type CommandType = ${commands.map(JSON.stringify).join(' | ')};\n`;
let rust = header + '#![allow(dead_code)]\n' + `pub const EVENT_TYPES: &[&str] = &[${events.map(JSON.stringify).join(', ')}];\n`;
ts += structure('EventEnvelope', schema, 'ts');
rust += structure('EventEnvelope', schema, 'rust');
for (const [name, definition] of Object.entries(schema.$defs)) {
  ts += structure(name, definition, 'ts');
  rust += structure(name, definition, 'rust');
}
ts += 'export type ClientCommand =\n' + Object.entries(schema['x-command-payloads']).map(([name, value]) => `  | { type: ${JSON.stringify(name)}; data: ${value} }`).join('\n') + ';\n';
for (const [file, content] of [['src/protocol/generated.d.ts', ts], ['rust/bahulam-tui/src/protocol.rs', rust]]) {
  const target = new URL(file, root);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error(`${file} is stale. Run npm run protocol:generate.`);
  } else fs.writeFileSync(target, content);
}
console.log(check ? 'Protocol generated files are current.' : 'Protocol types generated.');
